"""Contracts and serialization for Subsystem S5.2.B (Evidence Ledger).

INVARIANTS:
1. Ledger is neutral: records facts without computing student mastery.
2. Hash chaining is tamper-evident via canonical SHA-256 serialization.
3. Strict commit monotonicity: entry_index and committed_at strictly advance.
4. Duplicate evidence records are strictly forbidden (DuplicateEvidenceError).
5. Explicit HistoryCutoffMode (COMMIT_TIME vs EVENT_TIME).
"""

from datetime import datetime
from enum import Enum
import hashlib
import json
from typing import Any, Dict, Optional
from pydantic import ConfigDict, Field

from study_engine.contracts.base import BaseContract
from study_engine.state.policy_contracts import EvidenceRecord


class HistoryCutoffMode(str, Enum):
    """Temporal reference mode for historical ledger queries."""

    COMMIT_TIME = "COMMIT_TIME"
    EVENT_TIME = "EVENT_TIME"


class LedgerIntegrityStatus(str, Enum):
    """Integrity status evaluation of an evidence ledger hash chain."""

    VALID = "VALID"
    HASH_CHAIN_BROKEN = "HASH_CHAIN_BROKEN"
    NON_MONOTONIC_COMMIT = "NON_MONOTONIC_COMMIT"
    DUPLICATE_EVIDENCE_ID = "DUPLICATE_EVIDENCE_ID"
    GENESIS_MISMATCH = "GENESIS_MISMATCH"
    CORRUPTED_ENTRY = "CORRUPTED_ENTRY"


class LedgerContractError(Exception):
    """Base exception for all evidence ledger violations."""


class DuplicateEvidenceError(LedgerContractError):
    """Raised when record with an existing record_id is appended."""


class InconsistentReplayError(LedgerContractError):
    """Raised when an attempt ID is re-submitted with a divergent assessment digest."""


class IdempotentReplayError(DuplicateEvidenceError):
    """Raised when an attempt ID is re-submitted with identical canonical assessment digest."""


class LedgerIntegrityViolationError(LedgerContractError):

    """Raised when ledger detects corruption or tampering in the hash chain."""


class NonMonotonicCommitError(LedgerContractError):
    """Raised when committed_at is earlier than the previous entry's commit."""


class EvidenceLedgerEntry(BaseContract):
    """Immutable, tamper-evident entry in the evidence ledger hash chain."""

    model_config = ConfigDict(frozen=True)

    entry_index: int = Field(
        ..., ge=0, description="Monotonically increasing 0-based entry index"
    )
    record: EvidenceRecord = Field(
        ..., description="The underlying evidence record"
    )
    parent_entry_hash: str = Field(
        ...,
        min_length=64,
        max_length=64,
        pattern=r"^[0-9a-f]{64}$",
        description="SHA-256 digest of previous entry ('0'*64 for genesis)",
    )
    entry_hash: str = Field(
        ...,
        min_length=64,
        max_length=64,
        pattern=r"^[0-9a-f]{64}$",
        description="SHA-256 digest of this canonicalized entry",
    )
    committed_at: datetime = Field(
        ..., description="UTC timestamp assigned by ledger at commit time"
    )


class LedgerIntegrityReport(BaseContract):
    """Audit report generated by verifying the ledger's cryptographic chain."""

    model_config = ConfigDict(frozen=True)

    status: LedgerIntegrityStatus = Field(
        ..., description="Overall verification status of ledger"
    )
    total_entries: int = Field(
        ..., ge=0, description="Total number of entries scanned"
    )
    valid_entries: int = Field(
        ..., ge=0, description="Number of sequentially verified entries"
    )
    first_invalid_index: Optional[int] = Field(
        default=None, description="Index of first corrupt entry if invalid"
    )
    tip_hash: Optional[str] = Field(
        default=None,
        min_length=64,
        max_length=64,
        description="Canonical hash of the latest valid entry",
    )
    details: str = Field(
        ..., min_length=1, description="Audit narrative or diagnosis"
    )


def canonicalize_ledger_entry_payload(
    entry_index: int,
    parent_entry_hash: str,
    record: EvidenceRecord,
    committed_at: datetime,
) -> bytes:
    """Produce deterministic UTF-8 byte payload for cryptographic hashing.

    Standardizes all keys, enums, dates (ISO 8601 UTC), and nested dicts.
    """
    # Serialize record deterministically
    rec_dict: Dict[str, Any] = {
        "record_id": record.record_id,
        "student_id": record.student_id,
        "node_id": record.node_id,
        "competency_id": record.competency_id,

        "evidence_type": record.evidence_type.value,
        "outcome": record.outcome.value,
        "score": round(record.score, 6),
        "timestamp": record.timestamp.isoformat(),
        "actor_type": record.actor_type.value,
        "actor_id": record.actor_id,
        "audit_verdict": record.audit_verdict,
        "tool_backend": record.tool_backend,
        "verifier_id": record.verifier_id,
        "rationale": record.rationale,
        "roadmap_revision_id": record.roadmap_revision_id,
        "policy_revision_id": record.policy_revision_id,
        "metadata": dict(sorted(record.metadata.items())),
    }

    payload = {
        "entry_index": entry_index,
        "parent_entry_hash": parent_entry_hash,
        "record": rec_dict,
        "committed_at": committed_at.isoformat(),
    }

    raw_json = json.dumps(
        payload,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=True,
    )
    return raw_json.encode("utf-8")


def compute_ledger_entry_hash(
    entry_index: int,
    parent_entry_hash: str,
    record: EvidenceRecord,
    committed_at: datetime,
) -> str:
    """Compute SHA-256 digest of canonicalized ledger entry payload."""
    payload_bytes = canonicalize_ledger_entry_payload(
        entry_index=entry_index,
        parent_entry_hash=parent_entry_hash,
        record=record,
        committed_at=committed_at,
    )
    return hashlib.sha256(payload_bytes).hexdigest()
