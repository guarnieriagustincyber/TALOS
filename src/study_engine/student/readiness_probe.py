"""Prerequisite Readiness Probe for Subsystem E3 (Student Cognitive Layer).

Evaluates prerequisite knowledge before starting a new topic using the curriculum DAG.
INVARIANTS:
1. Purely advisory: NEVER blocks student access or acts as a hard veto.
2. Diagnostic questions originate strictly from deterministic question banks or verified
   symbolic exercises (NEVER generated by an uncalibrated LLM).
3. Supports `plan_only=True` for non-interactive benchmark consistency vs `administer=True` (H8).
"""

from typing import Any, Callable, Dict, List, Optional

from study_engine.student.bkt_tracker import BKTTracker
from study_engine.student.contracts import (
    PrerequisiteAssessment,
    ReadinessDecision,
    ReadinessReport,
    classify_readiness,
    is_blocking_for_advance,
)


class ReadinessProbe:
    """Evaluates student mastery over prerequisite Knowledge Components before starting a topic."""

    def __init__(
        self,
        bkt: BKTTracker,
        get_prerequisites_fn: Optional[Callable[[str], List[str]]] = None,
        prerequisite_map: Optional[Dict[str, List[str]]] = None,
        diagnostic_bank: Optional[Dict[str, List[Dict[str, Any]]]] = None,
    ) -> None:
        self.bkt = bkt
        self._get_prerequisites_fn = get_prerequisites_fn
        self._prerequisite_map = prerequisite_map or {}
        self._diagnostic_bank = diagnostic_bank or {}

    def register_prerequisites(self, topic_id: str, prerequisites: List[str]) -> None:
        """Register prerequisite closure list for a given topic."""
        self._prerequisite_map[topic_id] = list(prerequisites)

    def get_prerequisites(self, topic_id: str) -> List[str]:
        """Fetch all transitive or direct prerequisites for topic_id."""
        if self._get_prerequisites_fn is not None:
            try:
                return self._get_prerequisites_fn(topic_id)
            except Exception:
                pass
        return self._prerequisite_map.get(topic_id, [])

    def classify_mastery(self, p_L: float) -> str:
        """Classify P(L) into standardized pedagogical tiers."""
        return classify_readiness(p_L)

    def make_decision(self, assessments: List[PrerequisiteAssessment]) -> ReadinessDecision:
        """Compute advisory recommendation based on count of missing prerequisites."""
        missing = [a for a in assessments if is_blocking_for_advance(a.status)]
        if not missing:
            return ReadinessDecision.START
        elif len(missing) <= 2:
            return ReadinessDecision.START_WITH_SCAFFOLD
        return ReadinessDecision.REMEDIATE_FIRST

    def assess(
        self,
        target_topic_id: str,
        plan_only: bool = True,
        administer: bool = False,
        interactive_answers: Optional[Dict[str, List[bool]]] = None,
    ) -> ReadinessReport:
        """Assess readiness for target_topic_id.

        Args:
            target_topic_id: Target curriculum node ID.
            plan_only: When True, uses existing BKT priors without administering questions (H8).
            administer: When True, administers deterministic questions for unattempted prereqs.
            interactive_answers: Predefined deterministic responses for testing diagnostic bank.
        """
        if not target_topic_id or not target_topic_id.strip():
            raise ValueError("target_topic_id cannot be empty or whitespace (H4 Fail-Closed)")

        prerequisites = self.get_prerequisites(target_topic_id.strip())
        assessments: List[PrerequisiteAssessment] = []

        for prereq_id in prerequisites:
            bkt_state = self.bkt.get_state(prereq_id)

            if bkt_state.attempts > 0:
                status = self.classify_mastery(bkt_state.p_L)
                confidence = "high"
                p_L_val: Optional[float] = bkt_state.p_L
            else:
                if administer:
                    # Deterministic simulated or banked diagnostic administration
                    answers = (interactive_answers or {}).get(prereq_id, [False])
                    for ans in answers:
                        bkt_state = self.bkt.update(kc_id=prereq_id, correct=ans)
                    status = self.classify_mastery(bkt_state.p_L)
                    confidence = "medium"
                    p_L_val = bkt_state.p_L
                else:
                    # plan_only mode: no attempts recorded -> AUSENTE with low confidence
                    status = "AUSENTE"
                    confidence = "low"
                    p_L_val = None

            assessments.append(
                PrerequisiteAssessment(
                    kc_id=prereq_id,
                    status=status,
                    p_L=p_L_val,
                    confidence=confidence,
                )
            )

        decision = self.make_decision(assessments)
        missing_prereqs = [a for a in assessments if a.status == "AUSENTE"]

        return ReadinessReport(
            target_topic=target_topic_id.strip(),
            assessments=assessments,
            decision=decision,
            missing_prereqs=missing_prereqs,
            plan_only=plan_only and not administer,
        )
