"""Contracts and typed domain models for Subsystem E3 (Student Cognitive Layer).

Invariants:
1. Purely deterministic and verifiable: observations must declare a valid, typed source.
2. kc_id is mandatory and non-empty (fail-closed if omitted).
3. Zero LLM evaluation of mastery or student state.
"""

from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator


class ObservationSource(str, Enum):
    """Origin of the grading observation."""

    SYMBOLIC_VERIFIER = "SYMBOLIC_VERIFIER"
    EXACT_CORRECTOR = "EXACT_CORRECTOR"
    DIAGNOSTIC_BANK = "DIAGNOSTIC_BANK"
    UNVERIFIED_DIALOGUE = "UNVERIFIED_DIALOGUE"


class ExerciseFormat(str, Enum):
    """Pedagogical format of the evaluated task."""

    CLOSED_CHOICE = "CLOSED_CHOICE"
    SYMBOLIC_OPEN = "SYMBOLIC_OPEN"


class ObservationPayload(BaseModel):
    """Payload representing a single graded interaction observation."""

    model_config = ConfigDict(frozen=True)

    kc_id: str = Field(..., min_length=1, description="Knowledge Component / Topic identifier")
    correct: bool = Field(..., description="Whether the response was mathematically or formally correct")
    source: ObservationSource = Field(..., description="Verifiable evaluation source")
    format: ExerciseFormat = Field(default=ExerciseFormat.CLOSED_CHOICE, description="Format of the exercise")
    n_options: Optional[int] = Field(default=None, ge=2, description="Number of options if closed-choice")
    is_retry: bool = Field(default=False, description="Whether this was a correct attempt after a retry")
    is_recoverable_error: bool = Field(default=False, description="Whether an incorrect attempt was near-miss")
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="UTC timestamp of the observation",
    )

    @field_validator("kc_id")
    @classmethod
    def validate_kc_id(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("kc_id cannot be empty or whitespace (Fail-Closed H4)")
        return trimmed


class BKTState(BaseModel):
    """Mastery state for a single Knowledge Component (KC) under Corbett & Anderson (1995)."""

    kc_id: str = Field(..., min_length=1, description="Knowledge Component ID")
    p_L: float = Field(..., ge=0.0, le=1.0, description="Probability of mastery P(L)")
    p_T: float = Field(default=0.3, ge=0.0, le=1.0, description="Transition probability P(T)")
    p_G: float = Field(default=0.25, ge=0.0, le=1.0, description="Guess probability P(G)")
    p_S: float = Field(default=0.1, ge=0.0, le=1.0, description="Slip probability P(S)")
    last_update: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp of last update",
    )
    attempts: int = Field(default=0, ge=0, description="Total count of evaluated attempts")


class PrerequisiteAssessment(BaseModel):
    """Assessment of a single prerequisite topic."""

    kc_id: str = Field(..., min_length=1)
    status: str = Field(..., description="DOMINADO | NOCIÓN | EN_PROCESO | AUSENTE")
    p_L: Optional[float] = Field(default=None, ge=0.0, le=1.0)
    confidence: str = Field(default="low", description="high | low")


class ReadinessDecision(str, Enum):
    """Readiness decision for starting a target topic."""

    START = "START"
    START_WITH_SCAFFOLD = "START_WITH_SCAFFOLD"
    REMEDIATE_FIRST = "REMEDIATE_FIRST"


class ReadinessReport(BaseModel):
    """Report generated by ReadinessProbe before starting a topic."""

    target_topic: str = Field(..., min_length=1)
    assessments: List[PrerequisiteAssessment] = Field(default_factory=list)
    decision: ReadinessDecision = Field(...)
    missing_prereqs: List[PrerequisiteAssessment] = Field(default_factory=list)
    plan_only: bool = Field(default=True, description="Whether evaluated without interactive administration")


class RemediationOption(str, Enum):
    """Available pedagogical remediation paths upon lagging prerequisite."""

    PAUSE_AND_REMEDIATE = "PAUSE_AND_REMEDIATE"
    NOTE_AND_CONTINUE = "NOTE_AND_CONTINUE"
    DUAL_TRACK = "DUAL_TRACK"


class RemediationInterrupt(BaseModel):
    """Interrupt event emitted when a prerequisite fails during a study session."""

    kc_id: str = Field(..., min_length=1)
    p_L: float = Field(..., ge=0.0, le=1.0)
    reason: str = Field(default="Prerequisito flaqueó durante estudio")
    options: List[RemediationOption] = Field(
        default_factory=lambda: [
            RemediationOption.PAUSE_AND_REMEDIATE,
            RemediationOption.NOTE_AND_CONTINUE,
            RemediationOption.DUAL_TRACK,
        ]
    )
    current_topic_id: str = Field(..., min_length=1)
    chosen_option: Optional[RemediationOption] = Field(default=None)


class AnchorState(BaseModel):
    """Spaced repetition state for a conceptual anchor under SM-2."""

    anchor_id: str = Field(..., min_length=1)
    interval: int = Field(default=1, ge=1, description="Interval in days")
    repetitions: int = Field(default=0, ge=0, description="Repetition count")
    EF: float = Field(default=2.5, ge=1.3, description="Easiness Factor (>= 1.3)")
    next_review: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Due timestamp for next review",
    )
    last_quality: int = Field(default=5, ge=0, le=5, description="Last SM-2 quality grade (0-5)")
    updated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp of last SM-2 review update",
    )


READINESS_DOMINADO = 0.70
READINESS_NOCION = 0.35
BLOCKING_STATES = frozenset({"AUSENTE", "EN_PROCESO"})


def classify_readiness(p_L: Optional[float]) -> str:
    """Estado descriptivo de dominio. Única fuente de verdad de umbrales."""
    if p_L is None:
        return "AUSENTE"
    if p_L >= READINESS_DOMINADO:
        return "DOMINADO"
    if p_L >= READINESS_NOCION:
        return "NOCIÓN"
    return "EN_PROCESO"


def is_blocking_for_advance(estado: str) -> bool:
    """¿Este prerrequisito impide avanzar? AUSENTE y EN_PROCESO bloquean."""
    return estado in BLOCKING_STATES


def remediation_kind(estado: str) -> Optional[str]:
    if estado == "AUSENTE":
        return "SCAFFOLD_FROM_ZERO"
    if estado == "EN_PROCESO":
        return "TARGETED_REMEDIATION"
    if estado == "NOCIÓN":
        return "LIGHT_REVIEW"
    return None
