def main():
    gen = ExerciseGenerator()

    # Load the 6 human-certified expert exercises first
    store_path = Path("data/pedagogy/exercises/qualifiable_exercises.json")
    existing = json.loads(store_path.read_text(encoding="utf-8")) if store_path.exists() else []
    human_exercises = [e for e in existing if e.get("extraction_method") == "expert_transcription_from_corpus"]

    print(f"Preserving {len(human_exercises)} human expert certified exercises.")

    all_specs = curriculum_specs + additional_specs
    print(f"Processing {len(all_specs)} pedagogical exercise specifications...")

    all_certified = []
    # Add human exercises first with real computed content_hash
    for hex_dict in human_exercises:
        hex_dict["content_hash"] = gen.compute_content_hash(
            kc_id=hex_dict["kc_id"],
            prompt=hex_dict["prompt"],
            expected_answer=hex_dict["expected_answer"],
            exercise_type=ExerciseType(hex_dict["exercise_type"]),
            options=hex_dict.get("options"),
        )
        all_certified.append(hex_dict)

    # Process and certify the domain exercises
    idx = 1
    rejected_count = 0
    approved_count = 0

    for spec in all_specs:
        kc_id, src_id, loc, ex_type, prompt, answer, opts, expl = spec
        ex_id = f"ex_qual_{kc_id}_{ex_type.value.lower()}_{idx:02d}"
        idx += 1

        cand = gen.create_candidate(
            exercise_id=ex_id,
            source_id=src_id,
            source_location=loc,
            source_hash="0" * 64,
            kc_id=kc_id,
            prompt=prompt,
            exercise_type=ex_type,
            expected_answer=answer,
            options=opts,
            solution_explanation=expl,
        )

        certified = gen.certify_candidate(cand)
        if certified:
            approved_count += 1
            all_certified.append(certified.to_dict())
        else:
            rejected_count += 1
            is_valid, viols = gen.verify_candidate_integrity(cand)
            print(f"FAILED TO CERTIFY {ex_id}: {viols}")

    print(f"\nGenerated: {approved_count} approved, {rejected_count} rejected.")
    print(f"Total Certified in catalog: {len(all_certified)}")

    covered_kcs = {e["kc_id"] for e in all_certified}
    print(f"Unique KCs covered: {len(covered_kcs)}")

    # Write out qualifiable_exercises.json
    store_path.write_text(json.dumps(all_certified, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"Successfully updated {store_path}")


if __name__ == "__main__":
    main()
